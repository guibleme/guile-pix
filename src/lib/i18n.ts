const MESSAGES_BY_LOCALE: Record<Locale, Record<string, string>> = {
  en: EN_MESSAGES,
  es: ES_MESSAGES,
  ja: JA_MESSAGES,
};

function isLocale(value: string | null | undefined): value is Locale {
  if (!value) return false;
  return LOCALES.includes(value as Locale);
}

function isLocalePreference(value: string | null | undefined): value is LocalePreference {
  if (!value) return false;
  return value === 'auto' || isLocale(value);
}

export function readStoredLocale(): Locale | null {
  const preference = readStoredLocalePreference();
  if (preference === 'auto' || !preference) return null;
  return preference;
}

export function writeStoredLocale(locale: Locale): void {
  writeStoredLocalePreference(locale);
}

export function readStoredLocalePreference(): LocalePreference | null {
  if (typeof window === 'undefined') return null;
  const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY) ?? window.localStorage.getItem(LEGACY_LOCALE_STORAGE_KEY);
  if (!isLocalePreference(stored)) return null;
  return stored;
}

export function writeStoredLocalePreference(preference: LocalePreference): void {
  if (typeof window === 'undefined') return;
  window.localStorage.setItem(LOCALE_STORAGE_KEY, preference);
  window.localStorage.removeItem(LEGACY_LOCALE_STORAGE_KEY);
}

export function resolveLocaleFromPreference(preference: LocalePreference): Locale {
  if (preference === 'auto') return detectPreferredLocale();
  return preference;
}

export function detectPreferredLocale(): Locale {
  if (typeof navigator === 'undefined') return DEFAULT_LOCALE;
  const candidates = [...(navigator.languages ?? []), navigator.language].filter(Boolean);
  for (const candidate of candidates) {
    const normalized = candidate.toLowerCase();
    if (normalized.startsWith('ja')) return 'ja';
    if (normalized.startsWith('es')) return 'es';
    if (normalized.startsWith('en')) return 'en';
  }
  return DEFAULT_LOCALE;
}

export function localeToHtmlLang(locale: Locale): string {
  switch (locale) {
    case 'ja':
      return 'ja';
    case 'es':
      return 'es';
    default:
      return 'en';
  }
}

export function isDefaultProjectName(name: string): boolean {
  const normalized = name.trim();
  if (!normalized) return false;
  const defaults = new Set([
    EN_MESSAGES['newProject.defaultName'],
    ES_MESSAGES['newProject.defaultName'],
    JA_MESSAGES['newProject.defaultName'],
    'Untitled Sprite',
  ].filter(Boolean));
  return defaults.has(normalized);
}

function interpolate(message: string, params?: MessageParams): string {
  if (!params) return message;
  return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, key: string) => {
    const value = params[key];
    if (typeof value === 'undefined') return `{${key}}`;
    return String(value);
  });
}

export function translate(
  locale: Locale,
  key: string,
  fallback?: string,
  params?: MessageParams
): string {
  const byLocale = MESSAGES_BY_LOCALE[locale] ?? EN_MESSAGES;
  const template = byLocale[key] ?? EN_MESSAGES[key] ?? fallback ?? key;
  return interpolate(template, params);
}
