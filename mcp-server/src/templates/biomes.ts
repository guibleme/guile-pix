/**
 * 16x16 biome-specific environment tile templates.
 * Alternative biome versions of basic ground/wall tiles.
 * Each tile is designed to tile seamlessly with full coverage.
 * Uses the DB16 palette for all color schemes.
 *
 * Templates reuse the same SpriteRegion roles from humanoid16.ts
 * to stay compatible with the existing rendering/coloring pipeline.
 *
 * Role mapping for biome tiles:
 * - 'body'      = main fill / ground base
 * - 'head'      = secondary element / variation patches
 * - 'accessory' = detail highlights / surface accents
 * - 'eye'       = special accent dots (sparkle, glow)
 * - 'belt'      = border / edge / crack lines
 * - 'leg'       = shadow / darker area / depth
 * - 'arm'       = thin detail lines (cracks, veins, streaks)
 *
 * Tiles included:
 * - SNOW_GROUND_16   Snow-covered ground with blue shadows
 * - ICE_FLOOR_16     Frozen ice with highlight streaks and cracks
 * - JUNGLE_FLOOR_16  Dense jungle ground with leaf litter and vines
 * - DESERT_SAND_16   Desert sand with wind-swept ripple pattern
 * - SWAMP_16         Murky swamp with lily pads and bubbles
 * - CAVE_WALL_16     Rocky cave wall with mineral sparkles
 * - CRYSTAL_CAVE_16  Crystal-lined cave with glowing formations
 * - VOLCANO_FLOOR_16 Volcanic rock with magma crack fissures
 */

